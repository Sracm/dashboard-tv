SELECT CAB.CODEMP
        ,CAB.AD_ORCORIG
        ,ITE.AD_SEQORIG_ORC
        ,(SELECT E.NOMEFANTASIA FROM TSIEMP E WHERE E.CODEMP = CAB.CODEMP)    empresa
        ,(SELECT SUM (I.VLRTOT - I.VLRDESC) FROM TGFITE I, TGFCAB C WHERE     C.NUNOTA = I.NUNOTA AND C.AD_ORCORIG = CAB.AD_ORCORIG AND I.CODPROD = ITE.CODPROD AND C.CODEMP = 501 AND C.TIPMOV = 'V')       VENDA500
        ,CAB.NUNOTA
        ,CAB.DTNEG
        ,CAB.DTENTSAI
        ,(SELECT uf FROM tsiufs WHERE coduf = (SELECT uf FROM  tsicid WHERE codcid=(SELECT codcid FROM tgfpar WHERE codparc=cab.codparc))) AS uf
        ,(SELECT nomecid FROM  tsicid WHERE codcid=(SELECT codcid FROM tgfpar WHERE codparc=cab.codparc)) as cidade
        ,(SELECT apelido FROM tgfven WHERE codvend=cab.codvend) AS vendedor
        ,(SELECT apelido FROM tgfven ven WHERE ven.codvend=(SELECT codger FROM tgfven WHERE codvend =  cab.codvend)) AS gestor
        ,(SELECT tpp.descrtipparc FROM tgftpp tpp WHERE tpp.codtipparc=PAR.codtipparc) AS perfil_cli
        ,(SELECT descricao FROM TGFGCB WHERE codgrupo=PAR.codgrupo) AS grupo_cli
        ,CAB.CODPARC
        ,PAR.NOMEPARC
        ,TOP.DESCROPER
        ,(SELECT G.DESCRGRUPOPROD FROM TGFGRU G WHERE     G.CODGRUPOPROD = CASE WHEN LENGTH(TO_CHAR(PRO.codgrupoprod))=7 THEN RPAD(SUBSTR(TO_CHAR(PRO.codgrupoprod),1,1),7,'0') ELSE  RPAD(SUBSTR(TO_CHAR(PRO.codgrupoprod),1,2),8,'0') END) GRUPO_GERAL
        ,(SELECT G.DESCRGRUPOPROD FROM TGFGRU G WHERE     G.CODGRUPOPROD = CASE WHEN LENGTH(TO_CHAR(PRO.codgrupoprod))=7 THEN RPAD(SUBSTR(TO_CHAR(PRO.codgrupoprod),1,4),7,'0') ELSE  RPAD(SUBSTR(TO_CHAR(PRO.codgrupoprod),1,5),8,'0') END) GRUPO_Sintetico
        ,GRU.DESCRGRUPOPROD AS GRUPO_analitico
        ,PRO.marca
        ,ITE.CODPROD
        ,PRO.DESCRPROD AS PRODUTO
        ,PRO.REFERENCIA As sku_mq
        ,(ITE.VLRTOT - ITE.VLRDESC) AS VALOR
        ,((ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED + ITE.VLRSUBST + ITE.VLRIPI) * VCA.INDITENSBRUTO) * CASE WHEN TOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END * DECODE(CAB.TIPMOV,'D',0,'V',1) AS VALORVENDA
        ,CASE WHEN  CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'N' THEN (ITE.QTDNEG) END * DECODE(CAB.TIPMOV,'D',0,'V',1) AS QTDVENDIDA
        ,CASE WHEN TOP.GOLDEV = -1 THEN ITE.QTDNEG * (-1) ELSE 0 END AS QTDDEVOLVIDA
        ,CASE WHEN CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'N' THEN (F_OBTEM_CUSTO_MQ (CAB.CODEMP, ITE.CODPROD, CAB.DTNEG, CAB.DTNEG) * ITE.QTDNEG) END * DECODE(CAB.TIPMOV,'D',0,'V',1) * (CASE WHEN CAB.CODTIPOPER=11000 THEN 0 ELSE 1 END) AS CUSTOGER
        , CASE WHEN CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'N' THEN 
	        NVL(((SELECT MAX(CUS.CUSSEMICM)    FROM TGFCUS CUS
    	    WHERE CUS.CODPROD = ITE.CODPROD AND ITE.CODEMP = CUS.CODEMP AND CUS.DTATUAL = (SELECT MAX (CN.DTATUAL) FROM TGFCUS CN 	WHERE CN.CODPROD = CUS.CODPROD 	AND CN.DTATUAL <= CAB.DTNEG AND CN.CODLOCAl = CUS.CODLOCAL AND CN.CODEMP = CUS.CODEMP ))  ), 
        	(ITE.VLRTOT - ITE.VLRDESC + ITE.VLRSUBST + ITE.VLRIPI) * VCA.INDITENSBRUTO / (CASE WHEN ITE.QTDNEG=0 THEN 1 ELSE ITE.QTDNEG END) ) * ITE.QTDNEG END  * DECODE(CAB.TIPMOV,'D',0,'V',1) * (CASE WHEN CAB.CODTIPOPER=11000 THEN 0 ELSE 1 END) AS CUSTOMEDSEMICMS
        ,TRUNC (CASE WHEN CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'N' THEN (F_OBTEM_CUSTO_MQ (CAB.CODEMP, ITE.CODPROD, CAB.DTNEG, CAB.DTNEG)) END,4) * DECODE(CAB.TIPMOV,'D',0,'V',1) * (CASE WHEN CAB.CODTIPOPER=11000 THEN 0 ELSE 1 END) AS CUSTOMEDIO
        ,ROUND ((((ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED + ITE.VLRSUBST + ITE.VLRIPI) * VCA.INDITENSBRUTO) *
            CASE WHEN TOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END * DECODE(CAB.TIPMOV,'D',-1,'V',1)-F_OBTEM_FRETEITE(CAB.NUNOTA,ITE.SEQUENCIA)) / 
                CASE WHEN (CASE WHEN CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'N' THEN NVL(ITE.QTDNEG,1) * DECODE(CAB.TIPMOV,'D',-1,'V',1) END) = 0 THEN 1 
                    ELSE CASE WHEN CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'N' THEN NVL(ITE.QTDNEG,1) * DECODE(CAB.TIPMOV,'D',-1,'V',1) END END,4) AS PRECOMED
        ,NVL ( CASE WHEN NVL (TOP.BONIFICACAO, 'N') = 'S' THEN NVL ((  ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED + ITE.VLRSUBST + ITE.VLRIPI),0) END,0) AS VLRBONIFICADO
        ,NVL (CASE WHEN NVL (TOP.BONIFICACAO, 'N') = 'S' THEN (ITE.QTDNEG) END,0) AS QTDBONIFIC
        ,NVL (CASE WHEN CAB.CODEMP <> 501 AND NVL (TOP.BONIFICACAO, 'N') = 'S' THEN (F_OBTEM_CUSTO_MQ (CAB.CODEMP, ITE.CODPROD, CAB.DTNEG, CAB.DTNEG) * ITE.QTDNEG) END,0) AS CUSTOBONIF
        ,F_OBTEM_IMPOSTOSITE(CAB.NUNOTA,ITE.SEQUENCIA) AS IMPOST
        ,F_OBTEM_FRETEITE(CAB.NUNOTA,ITE.SEQUENCIA) AS FRETE
        ,((ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED + ITE.VLRSUBST + ITE.VLRIPI) * VCA.INDITENSBRUTO) * CASE WHEN TOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END * DECODE(CAB.TIPMOV,'D',1,'V',0) AS VALORDEVOLUCAO
        ,(SELECT nomeparc FROM tgfpar WHERE codparc=cab.codparctransp) AS transportadora
        ,(SELECT ad_dono FROM tgfpar WHERE codparc=par.codparcmatriz) AS dono
        ,CAB.TIPMOV
        ,(SELECT ORIGPROD FROM TGFPRO WHERE CODPROD=ITE.CODPROD) AS ORIGEM
        ,(SELECT ESTOQUE-RESERVADO FROM TGFEST WHERE TIPO='P' AND CODPARC=0 AND CODLOCAL=2 AND CODPROD=ITE.CODPROD AND CODEMP=CAB.CODEMP) AS SALDOESTOQUE
        ,(SELECT ESTOQUE-RESERVADO FROM TGFEST WHERE TIPO='P' AND CODPARC=0 AND CODLOCAL=2 AND CODPROD=ITE.CODPROD AND CODEMP=2) AS SALDOESTOQUE_MCRSC
    FROM TGFCAB CAB,
         TGFITE ITE,
         TGFTOP TOP,
         TGFPAR PAR,
         TGFTPP TPP,
         TGFGRU GRU,
         TGFPRO PRO,
         TSICID CID,
         VGFCAB VCA
   WHERE     CAB.CODTIPOPER = TOP.CODTIPOPER
          AND CAB.DHTIPOPER = TOP.DHALTER
          AND CAB.NUNOTA = ITE.NUNOTA
          AND CAB.CODPARC = PAR.CODPARC
          AND PRO.CODPROD = ITE.CODPROD
          AND PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
          AND PAR.CODTIPPARC = TPP.CODTIPPARC
          AND PAR.CODCID = CID.CODCID
          AND CAB.TIPMOV IN ('V', 'D')
          AND CAB.STATUSNOTA = 'L' 
          AND CAB.NUNOTA = VCA.NUNOTA
          AND (TOP.GOLSINAL = -1 OR BONIFICACAO='S')
          AND CAB.STATUSNOTA = 'L'
          AND (NOT EXISTS(SELECT 1 FROM TGFVAR VAR WHERE VAR.NUNOTA = ITE.NUNOTA AND VAR.NUNOTAORIG = VAR.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA))
          AND (TOP.ATUALFINTERC <> 'N' OR TOP.ATUALESTTERC = 'N' OR  ITE.TERCEIROS <> 'S')
          AND ITE.SEQUENCIA > 0    
          AND TOP.GOLDEV IN (0, 1, -1)
          AND CAB.DTENTSAI >= TO_DATE('01/01/2018','DD/MM/YYYY')
