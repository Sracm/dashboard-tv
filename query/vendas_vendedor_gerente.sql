SELECT codvend
         ,(SELECT TGFVEN.APELIDO  FROM TGFVEN WHERE (TGFVEN.CODVEND =  temp1.CODVEND )) AS vendedor
         ,(SELECT TGFVEN.APELIDO  FROM TGFVEN WHERE TGFVEN.CODVEND = (SELECT TGFVEN.codger FROM TGFVEN WHERE TGFVEN.CODVEND =temp1.CODVEND )) AS gerente
         ,DTENTSAI
         ,SUM(vendas) AS vendas
         ,(SUM(vendas)+ SUM(DEVOLUC)) AS TotalFat
         ,SUM(pedidos) AS pedidos
        ,(SUM(vendas)+SUM(pedidos)+ SUM(DEVOLUC)) AS TotalPrevisto
        ,CODEMP
        ,codprod

FROM (
/*----------------------------
Venda
------------------------------*/
SELECT TGFCAB.CODVEND
        ,TGFCAB.CODPARC
        ,TGFCAB.CODEMP
        ,TGFCAB.DTENTSAI
      ,SUM( (ITE.VLRTOT - ITE.VLRDESC)  * CASE WHEN TGFTOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END * TGFTOP.GOLDEV ) AS vendas
    ,0 AS devoluc
      ,0 AS pedidos
        ,SUM(ITE.VLRSUBST*(-1)) AS VLRSUBST
        ,SUM(ITE.VLRIPI*(-1) * CASE WHEN TGFTOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END ) AS VLRIPI
        ,ite.codprod
FROM TGFCAB
, TGFTOP
, TGFVEN
, TGFITE ITE
, VGFCAB VCA
WHERE TGFCAB.CODTIPOPER = TGFTOP.CODTIPOPER
AND TGFCAB.DHTIPOPER = TGFTOP.DHALTER
AND TGFCAB.CODVEND = TGFVEN.CODVEND
AND TGFTOP.GOLSINAL = -1
AND TGFCAB.STATUSNOTA = 'L'
AND (NOT EXISTS(SELECT 1 FROM TGFVAR VAR WHERE VAR.NUNOTA = ITE.NUNOTA AND VAR.NUNOTAORIG = VAR.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA))
AND (TGFTOP.ATUALFINTERC <> 'N' OR TGFTOP.ATUALESTTERC = 'N' OR  ITE.TERCEIROS <> 'S')
AND ITE.SEQUENCIA > 0
AND TGFCAB.NUNOTA = ITE.NUNOTA
AND TGFCAB.NUNOTA = VCA.NUNOTA
AND TGFTOP.GOLDEV = 1
GROUP BY TGFCAB.CODVEND, TGFCAB.NUNOTA, TGFCAB.CODPARC, TGFCAB.CODEMP, TGFCAB.DTENTSAI, ite.codprod

UNION ALL
/*----------------------------
Devolução
------------------------------*/
SELECT TGFCAB.CODVEND
        ,TGFCAB.CODPARC
        ,TGFCAB.CODEMP
        ,TGFCAB.DTENTSAI
      ,0 AS vendas
      ,SUM( (ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED)  * CASE WHEN TGFTOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END * TGFTOP.GOLDEV ) AS devoluc
      ,0 AS pedidos
      ,0 AS VLRSUBST
      ,SUM(ITE.VLRIPI) AS VLRIPI
      ,ite.codprod
FROM TGFCAB
, TGFTOP
, TGFVEN
, TGFITE ITE
, VGFCAB VCA
WHERE TGFCAB.CODTIPOPER = TGFTOP.CODTIPOPER
AND TGFCAB.DHTIPOPER = TGFTOP.DHALTER
AND TGFCAB.CODVEND = TGFVEN.CODVEND
AND TGFTOP.GOLSINAL = -1
AND TGFCAB.STATUSNOTA = 'L'
AND (NOT EXISTS(SELECT 1 FROM TGFVAR VAR WHERE VAR.NUNOTA = ITE.NUNOTA AND VAR.NUNOTAORIG = VAR.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA))
AND (TGFTOP.ATUALFINTERC <> 'N' OR TGFTOP.ATUALESTTERC = 'N' OR  ITE.TERCEIROS <> 'S')
AND ITE.SEQUENCIA > 0
AND TGFCAB.NUNOTA = ITE.NUNOTA
AND TGFCAB.NUNOTA = VCA.NUNOTA
 AND TGFTOP.GOLDEV = -1
GROUP BY TGFCAB.CODVEND, TGFCAB.NUNOTA,TGFCAB.CODPARC,TGFCAB.CODEMP,TGFCAB.DTENTSAI,ite.codprod

UNION ALL
/*----------------------------
Pedido
------------------------------*/
SELECT  tgfcab.codvend
        ,TGFCAB.CODPARC
        ,TGFCAB.CODEMP
        ,TGFCAB.DTENTSAI
    ,0 AS vendas
       ,0 AS devoluc
      ,SUM( (ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED )  * CASE WHEN TGFTOP.BONIFICACAO = 'S' THEN 0 ELSE 1 END /
          CASE WHEN TGFCAB.CODEMP=2 AND CODCENCUS NOT IN (1050000)  THEN (((SELECT COALESCE(percentual,0) FROM TGFIPI WHERE CODIPI=(SELECT CODIPI FROM TGFPRO WHERE CODPROD=ITE.CODPROD))/100)+1) ELSE 1 END
        ) AS pedidos
       ,0 AS VLRSUBST
       ,0 AS VLRIPI
       ,ite.codprod
FROM tgfcab INNER JOIN tgfite ITE ON (tgfcab.nunota = ITE.nunota)
INNER JOIN TGFTOP ON (TGFCAB.CODTIPOPER = TGFTOP.CODTIPOPER AND TGFCAB.DHTIPOPER = TGFTOP.DHALTER)
WHERE tgfcab.tipmov='P' AND NVL(tgftop.orcamento,'N')<>'S'
AND tgfcab.codtipoper NOT IN (3110,3122)
AND NOT EXISTS (SELECT 1 FROM tgfvar WHERE nunotaorig=tgfcab.nunota)

GROUP BY tgfcab.codvend,TGFCAB.CODPARC,TGFCAB.CODEMP,TGFCAB.DTENTSAI, ite.codprod
) temp1
WHERE temp1.CODVEND NOT IN (22362,9307,2807,413,14825, 7222, 7221,16271, 1)
AND temp1.CODVEND NOT IN (SELECT codvend FROM tgfven WHERE codger=9307)
--and temp1.codvend=300 AND dtentsai between '01/02/2025' AND '28/02/2025'
GROUP BY temp1.codvend,temp1.codparc,TEMP1.CODEMP, temp1.dtentsai, temp1.codprod
